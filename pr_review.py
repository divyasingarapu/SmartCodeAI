
import json
import os
import subprocess
import sys
from pathlib import Path

from analyzer import analyze_code
from security_scanner import scan_security


ROOT = Path.cwd()
OUTPUT_FILE = ROOT / "pr-review-report.md"


def get_changed_python_files():
    """Find Python files changed in the pull request."""
    base_ref = os.environ.get("GITHUB_BASE_REF")

    if base_ref:
        subprocess.run(
            ["git", "fetch", "origin", base_ref, "--depth=1"],
            check=True,
            capture_output=True,
            text=True,
        )

        diff_range = f"origin/{base_ref}...HEAD"
    else:
        # Allow running the script locally for a smoke test.
        diff_range = "HEAD~1...HEAD"

    result = subprocess.run(
        [
            "git", "diff", "--name-only", "--diff-filter=ACMR",
            diff_range, "--", "*.py"
        ],
        check=True,
        capture_output=True,
        text=True,
    )

    return [
        Path(name)
        for name in result.stdout.splitlines()
        if Path(name).suffix == ".py"
        and Path(name).is_file()
    ]


def review_file(path):
    """Run existing quality and security checks on one file."""
    source = path.read_text(encoding="utf-8", errors="replace")

    quality_issues = analyze_code(source, "python")
    security_issues = scan_security(source, "python")

    return quality_issues, security_issues


def main():
    try:
        changed_files = get_changed_python_files()
    except subprocess.CalledProcessError as error:
        print("Could not identify changed Python files.")
        print(error.stderr or str(error))
        return 1

    report = [
        "# SmartCode AI — Pull Request Review",
        "",
        f"Python files reviewed: {len(changed_files)}",
        "",
    ]

    total_issues = 0

    if not changed_files:
        report.extend([
            "No changed Python files were found in this pull request.",
            "",
        ])

    for path in changed_files:
        quality, security = review_file(path)
        issues = quality + security
        total_issues += len(issues)

        report.extend([
            f"## `{path.as_posix()}`",
            "",
        ])

        if not issues:
            report.extend(["No issues reported.", ""])
            continue

        for issue in issues:
            issue_type = issue.get("type", "Issue")
            severity = issue.get("severity", "unknown")
            line = issue.get("line", "?")
            message = issue.get("message", "No message provided")
            suggestion = issue.get("suggestion", "")

            report.append(
                f"- **{severity.upper()} — {issue_type}**, "
                f"line {line}: {message}"
            )

            if suggestion:
                report.append(f"  - Suggestion: {suggestion}")

            report.append("")

    report.extend([
        "---",
        f"**Total findings:** {total_issues}",
        "",
        "Generated by SmartCode AI.",
    ])

    OUTPUT_FILE.write_text(
        "\n".join(report) + "\n",
        encoding="utf-8",
    )

    print("\n".join(report))
    print(f"\nReport saved to: {OUTPUT_FILE}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
